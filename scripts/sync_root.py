"""Mirror site/ to the repository root for Vercel.

Vercel serves whatever is at the root of the repo. The generators, though, all
write to site/ - build_site.py emits tokens.css, build_pages.py writes the HTML,
extract_logo.py writes the logo variants. So the deployable lives in two places,
which is exactly the arrangement that rots: someone regenerates the site, pushes
without re-running this, and the live site quietly serves last month's markup
while the repo's own copy says otherwise.

So the duplication is made explicit and policed rather than left to memory:

    python scripts/sync_root.py          copy site/ to the root, update manifest
    python scripts/sync_root.py --check  fail if the two have drifted

--check is the gate. Run it before every commit.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
MANIFEST = ROOT / ".sync-manifest.json"

# Written by hand at the repo root, never mirrored from site/. Mirroring them
# would let a regeneration delete the README.
ROOT_OWNED = {".gitignore", ".sync-manifest.json", "README.md",
              "scripts", "docs", "research", "site", ".github"}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def site_files() -> list[Path]:
    return sorted(p for p in SITE.rglob("*") if p.is_file())


def rel(p: Path) -> str:
    return p.relative_to(SITE).as_posix()


def sync() -> int:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else {}
    previous = set(manifest.get("mirrored", []))

    written, unchanged = 0, 0
    current: set[str] = set()

    for src in site_files():
        r = rel(src)
        current.add(r)
        dst = ROOT / r
        if dst.exists() and digest(dst) == digest(src):
            unchanged += 1
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        written += 1

    # Drop root files this script previously mirrored but site/ no longer has.
    removed = 0
    for r in sorted(previous - current):
        stale = ROOT / r
        if stale.is_file():
            stale.unlink()
            removed += 1
            print(f"  removed stale  {r}")
        elif stale.is_dir() and not any(stale.iterdir()):
            stale.rmdir()

    MANIFEST.write_text(json.dumps({
        "source": "site/",
        "mirrored": sorted(current),
        "note": "Generated by scripts/sync_root.py. Do not hand-edit.",
    }, indent=2), encoding="utf-8")

    print(f"  mirrored {written} file(s), {unchanged} already current, "
          f"{removed} removed")
    print(f"  manifest  -> {MANIFEST.name}  ({len(current)} paths)")
    return 0


def check() -> int:
    problems: list[str] = []
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else {}
    expected = set(manifest.get("mirrored", []))
    actual = {rel(p) for p in site_files()}

    for r in sorted(expected - actual):
        problems.append(f"root has {r} but site/ no longer does")

    for src in site_files():
        r = rel(src)
        dst = ROOT / r
        if dst.name in ROOT_OWNED and not dst.exists():
            continue
        if not dst.exists():
            problems.append(f"missing at root: {r}   (run scripts/sync_root.py)")
        elif digest(dst) != digest(src):
            problems.append(f"differs: {r}   (run scripts/sync_root.py)")

    print(f"  {len(actual)} file(s) in site/, {len(expected)} in the manifest")
    if not problems:
        print("  root mirror is in sync with site/")
        return 0
    for p in problems:
        print(f"  DRIFT  {p}")
    print(f"\n  {len(problems)} drift(s). Vercel deploys the ROOT, so a stale "
          f"root means a stale live site.")
    return 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify instead of copying; exit 1 on drift")
    args = ap.parse_args()
    if not SITE.is_dir():
        print("!! site/ not found")
        return 1
    return check() if args.check else sync()


if __name__ == "__main__":
    raise SystemExit(main())
